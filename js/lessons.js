/** 由节拍表生成时间轴 */
export function buildTimeline(lesson, leadIn = 1.2) {
  const spb = 60 / lesson.bpm;
  let t = leadIn;
  const notes = lesson.notes
    .map((n, i) => {
      const beats = n.b ?? 1;
      if (n.m == null) {           // 休止符也要占拍，否则换气空档会消失
        t += beats * spb;
        return null;
      }
      const start = t;
      const end = start + beats * spb;
      t = end;
      return { index: 0, midi: n.m, start, end, beats, lyric: n.l || '' };
    })
    .filter(Boolean);
  notes.forEach((n, i) => { n.index = i; });
  return { notes, duration: t + 0.8, bpm: lesson.bpm, spb };
}

/** 用连续音高数组 + 独立歌词数组构造（歌词长度可小于音符数） */
function seq(pitches, lyrics = [], beats = null) {
  return pitches.map((m, i) => ({
    m,
    l: lyrics[i] || '',
    b: Array.isArray(beats) ? beats[i] : beats || 1,
  }));
}

/** 半音阶：from..to 含两端 */
function chromatic(from, to) {
  const out = [];
  const step = to >= from ? 1 : -1;
  for (let m = from; step > 0 ? m <= to : m >= to; m += step) out.push(m);
  return out;
}

